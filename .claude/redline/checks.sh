#!/usr/bin/env bash
#
# Redline gate for the Redline plugin's own repository. Runs the runnable part of the Verification
# Gate (.claude/commands/agent-os/shape-spec.md, steps 1 to 9) plus the git-state checks, and emits
# exactly one JSON object on stdout. Progress goes to stderr. Nothing in it is new policy; the gate
# text stays the source.
#
# Usage:
#   checks.sh <snapshot.json>              full run: commands + git block
#   checks.sh --baseline [snapshot.json]   commands only, git block is null
#   checks.sh --git-only <snapshot.json>   git block only, checks is []
#   checks.sh --verdict [--baseline | --git-only] [snapshot.json]
#                                          no run: the verdict of the run kept for this commit
#
# Environment:
#   REDLINE_OCTANE=1   set by the workflow when the approved plan touches app/Providers/,
#                      bootstrap/ or config/octane.php. Ignored here: no long-lived-process suite.
#
# The nine checks, in the gate's order:
#   syntax      ls scripts/*.sh | xargs -n1 bash -n && jq -e . hooks/hooks.json >/dev/null  (gate step 1: Syntax)
#   validate    claude plugin validate .  (gate step 2: Manifest)
#   guard       tests/guard-test.sh  (gate step 3: Guard)
#   loop        node tests/loop-test.mjs  (gate step 4: Loop)
#   prefs       tests/prefs-test.sh  (gate step 5: Prefs)
#   gate        tests/gate-test.sh  (gate step 6: Gate stamp)
#   setup       tests/setup-test.sh  (gate step 7: Setup)
#   gh          tests/gh-test.sh  (gate step 8: GitHub wrapper)
#   background  tests/background-test.sh  (gate step 9: Background)
# No formatter, so there is no recorded "fix" step.
# Baseline on 2026-10-26: 78 seconds, most of it the guard table (389 rows at about 60 ms each); the background harness waits about 11 s on its slice, limit and grace cases, so `checker: full` is the right mode.
#
# Snapshot: {"pr", "start_sha", "round_sha", "base_ref", "files": [...], "plan_paths": [...]}.
# Allowed changes are files + plan_paths + agent-os/specs/ + agent-os/standards/; anything else that
# changed since start_sha is unexpected. git.commits lists round_sha..HEAD, the round's own commits,
# or start_sha..HEAD when the snapshot has no round_sha.
#
# Exit 0 when every non-recorded check passed and git.unexpected_files and git.uncommitted are both
# empty, else 1. Usage errors exit 2, and so does a --verdict with no kept result for this commit,
# mode and snapshot. See README.md for the output contract.
#
# stdout is sized for the workflow and stays small whatever the pull request's size or the run's
# length. The full result is kept in a file outside the working tree, under redline-checks/ in
# TMPDIR (else /tmp), named under "kept" in the result; the comments in the script give the sizes
# and the file's place.
#
# Generated from .claude/redline/checks.json by scripts/redline-setup.sh checks: edit the JSON and
# regenerate; do not edit this file by hand. The last line of this header is the gate stamp: a hash
# of the gate's backticked text, written by scripts/redline-gate.sh stamp. A launch recomputes it
# from the gate and refuses to run when the two differ, so a gate step added later cannot go
# unnoticed. After bringing checks.json up to date with a changed gate, regenerate and restamp:
# scripts/redline-gate.sh stamp .claude/commands/agent-os/shape-spec.md .claude/redline/checks.sh
# redline-template: checks-template.sh v3
# redline-gate: .claude/commands/agent-os/shape-spec.md steps 1-9 sha256:c18b4c85922835cf7a1efe6a5bde159451a89cc8e1b3f7b496e625771883aafb

set -euo pipefail

# Files every round may change besides the plan's (a generated contract the gate regenerates,
# say). Repository-relative; a trailing / makes an entry a prefix.
ALWAYS_ALLOWED=()

mode="full"
verdict=0
snapshot=""
for arg in "$@"; do
    case "$arg" in
        --baseline) mode="baseline" ;;
        --git-only) mode="git-only" ;;
        --verdict) verdict=1 ;;
        -h|--help) sed -n '2,/^$/p' "$0" >&2; exit 2 ;;
        -*) echo "checks.sh: unknown flag $arg" >&2; exit 2 ;;
        *) snapshot="$arg" ;;
    esac
done

if [[ "$mode" != "baseline" && -z "$snapshot" ]]; then
    echo "checks.sh: a snapshot file is required unless --baseline is given" >&2
    exit 2
fi
if [[ -n "$snapshot" ]]; then
    snapshot="$(cd "$(dirname "$snapshot")" && pwd)/$(basename "$snapshot")"
    if ! jq -e '.start_sha and (.files | type == "array")' "$snapshot" >/dev/null 2>&1; then
        echo "checks.sh: $snapshot is not a snapshot (needs start_sha and files[])" >&2
        exit 2
    fi
fi

cd "$(git rev-parse --show-toplevel)"

# The kept result (#68). Every run writes its full result to one file outside the working tree:
#   <TMPDIR, else /tmp>/redline-checks/<root key>-<commit>.json
# The root key is git's hash of the physical path of this repository's top level, so two worktrees
# of one repository have two keys and never read each other's result. The commit is HEAD when the
# run started. A run first removes this root's earlier files, so a root has one kept result, the
# last run's. --verdict reads only the file for the current HEAD: once HEAD has moved the kept
# result is another commit's and is never read (exit 2), and the same for a result of another
# mode or another snapshot than the one asked for.
# The temp directory is read without quotes so that redline-setup.sh read-checks, which takes a
# quoted NAME="${ENV:-default}" line for one of the repository's own variables, passes it by.
root="$(pwd -P)"
head_sha="$(git rev-parse --verify --quiet HEAD || echo none)"
kept_dir=${TMPDIR:-/tmp}
kept_dir="${kept_dir%/}/redline-checks"
root_key="$(printf '%s' "$root" | git hash-object --stdin)"
kept="$kept_dir/$root_key-$head_sha.json"

# --verdict runs nothing. It prints what the kept run printed, less every check's output, for a
# caller whose tool could not show that run's result, and exits with that run's exit code.
if [[ $verdict -eq 1 ]]; then
    if [[ ! -f "$kept" ]]; then
        other=""
        for file in "$kept_dir/$root_key-"*.json; do
            if [[ -e "$file" ]]; then
                other="${file##*-}"
            fi
        done
        if [[ -n "$other" ]]; then
            echo "checks.sh: the kept result here is for commit ${other%.json}, and HEAD is now $head_sha; run the gate again" >&2
        else
            echo "checks.sh: no kept result for $root; run the gate first" >&2
        fi
        exit 2
    fi
    if ! jq -e --arg mode "$mode" --arg snapshot "$snapshot" '.mode == $mode and .snapshot == $snapshot' "$kept" >/dev/null 2>&1; then
        echo "checks.sh: the kept result is for $(jq -r '[.mode, .snapshot] | join(" ")' "$kept" 2>/dev/null || echo 'a run that cannot be read'), not for $mode $snapshot; run the gate again" >&2
        exit 2
    fi
    jq -c '.printed | .verdict = true | .checks |= map(del(.truncated, .stdout, .stderr))' "$kept"
    exit "$(jq -r '.exit' "$kept")"
fi

work="$(mktemp -d "${TMPDIR:-/tmp}/redline-checks.XXXXXX")"
trap 'rm -rf "$work"' EXIT

checks_full="$work/checks.full.jsonl"
: > "$checks_full"
checks_print="$work/checks.print.jsonl"
: > "$checks_print"
checks_ran="$work/checks.ran.jsonl"
: > "$checks_ran"
failed=0

# What stdout carries is sized for the workflow, so that the Bash tool shows the whole result
# inline however large the pull request and however long the run (#68). The tool shows stderr
# beside it, so the progress lines are counted too.
#
# A check that passed prints its name, its exit code and whether it is recorded: the workflow reads
# nothing else of it. A check that failed keeps its command, cut at cmd_max characters, and the
# tail of its output: up to keep_failed lines a stream, within one budget of bytes that all the
# failing checks share, split evenly among them in the final pass after every check has run;
# within a failing check each stream takes at least half of its share when both are long, and
# bytes one stream leaves unused go to the other (#7, R2-1). truncated is true when a line count
# or a byte allotment cut a stream. ANSI escapes and the other control bytes are taken out of
# every stream as it is captured, so each count and each cut reads plain text.
#
# The git block prints counts for the allowed paths, the changed files and the files the
# formatter touched, and prints unexpected_files and uncommitted whole, since those fail a round.
# commits holds the round's own commits (round_sha..HEAD), each subject cut at subject_max
# characters; commits_count counts every commit since start_sha.
#
# The budget, in bytes of stdout and stderr together, for twelve checks and a round of forty
# commits:
#   the envelope, the git block's fixed keys and the kept path     600
#   stderr, two short lines a check and four more                  960
#   a check that passed, 39 and its name                            60
#   a commit, 64 and its subject (subject_max, "...", saved ids)   174
#   a check that failed, 84, its name and its command              350
#   the failing checks' output, the budget once encoded         10,240
# A passing result is at most 600 + 960 + 12 x 60 + 40 x 174 = 9,240, under 10 KB. With every
# check failing it is at most 600 + 960 + 12 x 350 + 10,240 + 40 x 174 = 22,960, under 25 KB.
# Encoding as JSON adds a byte to each newline, tab, quote and backslash and nothing to any other
# byte left in a stream, so the output is at most twice the budget and a command at most twice
# cmd_max. Neither sum holds the number of files, of allowed paths or of commits since the start:
# those print as counts. An unexpected or uncommitted path adds its length and three bytes, and
# both lists are empty when the gate passes. tests/setup-test.sh runs both cases.
#
# The kept result holds what stdout leaves out: every check with its whole command and the last
# kept_lines lines of each stream (kept_cap bytes at most), the allowed and changed lists, and
# every commit since start_sha with its whole subject.
keep_failed=200 budget=5120 cmd_max=120 subject_max=100 kept_lines=200 kept_cap=65536

log() { printf 'checks.sh: %s\n' "$*" >&2; }

# plain: a stream without its ANSI escapes (colour and cursor sequences, a terminal title, a lone
# escape) or any other control byte but tab and newline. LC_ALL=C makes sed and tr read bytes, so
# output that is not UTF-8 passes through; the escape byte is written in the $'...' form, which
# BSD sed takes.
plain() {
    LC_ALL=C sed -e $'s|\x1b\\[[0-?]*[ -/]*[@-~]||g' -e $'s|\x1b\\][^\x07]*\x07||g' -e $'s|\x1b.||g' \
        | LC_ALL=C tr -d '\000-\010\013-\037\177'
}

# run_check <name> <recorded:0|1> <command string>
# Runs the command through bash -c so composite commands read as one check, and records it
# for the final pass, which writes its JSON once every check has run.
run_check() {
    local name="$1" recorded="$2" cmd="$3" code=0
    log "running $name"
    set +e
    bash -c "$cmd" >"$work/$name.out.raw" 2>"$work/$name.err.raw" </dev/null
    code=$?
    set -e
    plain <"$work/$name.out.raw" >"$work/$name.out"
    plain <"$work/$name.err.raw" >"$work/$name.err"
    rm -f "$work/$name.out.raw" "$work/$name.err.raw"
    if [[ $code -ne 0 && $recorded -eq 0 ]]; then
        failed=1
        log "$name FAILED (exit $code)"
    else
        log "$name exit $code"
    fi
    jq -n -c \
        --arg name "$name" --arg cmd "$cmd" --argjson exit "$code" \
        --argjson recorded "$([[ $recorded -eq 1 ]] && echo true || echo false)" \
        '{name: $name, cmd: $cmd, exit: $exit, recorded: $recorded}' \
        >> "$checks_ran"
}

# The final pass, run once after every check: writes each recorded check's JSON object in run order,
# once for the kept result ($checks_full) and once for stdout ($checks_print), its streams cut to
# the limits described above. Each failing check's share of the budget is budget / (number of
# failing checks), so the sum stays bounded.
emit_checks() {
    local failing share entry name code out_cap err_cap out_kept err_kept truncated
    failing=$(jq -s '[.[] | select(.exit != 0)] | length' "$checks_ran")
    share=$budget
    if [[ $failing -gt 0 ]]; then
        share=$((budget / failing))
    fi
    while IFS= read -r entry; do
        name=$(jq -r '.name' <<<"$entry")
        code=$(jq -r '.exit' <<<"$entry")
        jq -n -c \
            --argjson check "$entry" \
            --rawfile stdout <(tail -n "$kept_lines" "$work/$name.out" | tail -c "$kept_cap") \
            --rawfile stderr <(tail -n "$kept_lines" "$work/$name.err" | tail -c "$kept_cap") \
            '$check + {stdout: $stdout, stderr: $stderr}' \
            >> "$checks_full"
        if [[ $code -eq 0 ]]; then
            jq -c '{name, exit, recorded}' <<<"$entry" >> "$checks_print"
            continue
        fi
        out_kept=$(tail -n "$keep_failed" "$work/$name.out" | wc -c)
        err_kept=$(tail -n "$keep_failed" "$work/$name.err" | wc -c)
        err_cap=$((share / 2))
        if [[ $((share - out_kept)) -gt $err_cap ]]; then
            err_cap=$((share - out_kept))
        fi
        if [[ $err_kept -lt $err_cap ]]; then
            err_cap=$((err_kept))
        fi
        out_cap=$((share - err_cap))
        truncated=false
        if [[ $(wc -l <"$work/$name.out") -gt $keep_failed || $(wc -l <"$work/$name.err") -gt $keep_failed \
            || $(wc -c <"$work/$name.out") -gt $out_cap || $(wc -c <"$work/$name.err") -gt $err_cap ]]; then
            truncated=true
        fi
        jq -n -c \
            --argjson check "$entry" --argjson truncated "$truncated" --argjson cmd_max "$cmd_max" \
            --rawfile stdout <(tail -n "$keep_failed" "$work/$name.out" | tail -c "$out_cap") \
            --rawfile stderr <(tail -n "$keep_failed" "$work/$name.err" | tail -c "$err_cap") \
            '$check + {cmd: ($check.cmd | if length > $cmd_max then .[0:$cmd_max] + "..." else . end), truncated: $truncated, stdout: $stdout, stderr: $stderr}' \
            >> "$checks_print"
    done < "$checks_ran"
}

# Hash every file that differs from HEAD (modified, added, untracked) so the
# formatter's touches can be told apart from edits that were already there.
tree_state() {
    git status --porcelain=v1 -z --untracked-files=all \
        | tr '\0' '\n' \
        | sed -n 's/^.. //p' \
        | sed 's/^.* -> //' \
        | while IFS= read -r path; do
            if [[ -f "$path" ]]; then
                printf '%s %s\n' "$(git hash-object "$path")" "$path"
            else
                printf 'deleted %s\n' "$path"
            fi
        done | sort
}

# The PR's base as a ref that resolves here (the snapshot's base_ref, else origin/HEAD, else
# origin/main), for a check that diffs the change against its base. Returns 1 when none does.
base_ref() {
    local ref=""
    if [[ -n "$snapshot" ]]; then
        ref="$(jq -r '.base_ref // empty' "$snapshot")"
    fi
    if [[ -z "$ref" ]]; then
        ref="$(git symbolic-ref --quiet --short refs/remotes/origin/HEAD 2>/dev/null || echo origin/main)"
    fi
    if git rev-parse --verify --quiet "$ref" >/dev/null; then
        echo "$ref"
    elif git rev-parse --verify --quiet "origin/$ref" >/dev/null; then
        echo "origin/$ref"
    else
        log "base ref $ref resolves neither as $ref nor as origin/$ref"
        return 1
    fi
}

# lines_json <file>: the file's lines as one JSON array of strings.
lines_json() { jq -R . "$1" | jq -s -c .; }

# commits_json <file>: lines of <sha><US><subject>, as git log wrote them, as [{sha, message}].
commits_json() {
    jq -R --arg sep $'\x1f' 'split($sep) | {sha: .[0], message: (.[1] // "")}' "$1" | jq -s -c .
}

# cut_subjects: the same lines with each subject cut for stdout. A subject over subject_max
# characters is cut at the last space at or before subject_max and ends "...". The cut falls at a
# space so that it never splits a finding id into another one (R5-10 into R5-1). The workflow
# looks for a round's finding ids in these subjects, and a commit may name one late (a standards
# commit ends "finishing R1-1 and R1-4"), so every id in the part cut off is put back after the
# "...": both forms, R<round>-<n> and H<n>-<k>, standing as the workflow reads them, with no
# letter, digit or hyphen before.
cut_subjects() {
    awk -F $'\x1f' -v max="$subject_max" '{
        subject = $2
        if (length(subject) > max) {
            head = substr(subject, 1, max + 1)
            if (match(head, / [^ ]*$/)) { head = substr(head, 1, RSTART - 1) } else { head = substr(subject, 1, max) }
            rest = substr(subject, length(head) + 1)
            sub(/ +$/, "", head)
            subject = head "..."
            while (match(rest, /[RH][0-9]+-[0-9]+/)) { if (RSTART == 1 || substr(rest, RSTART - 1, 1) !~ /[A-Za-z0-9-]/) { subject = subject " " substr(rest, RSTART, RLENGTH) } rest = substr(rest, RSTART + RLENGTH) }  # the id rescue
        }
        printf "%s\x1f%s\n", $1, subject
    }'
}

formatter_touched="$work/formatter_touched"
: > "$formatter_touched"

if [[ "$mode" != "git-only" ]]; then
    # No formatter: nothing touches a file, so formatter_touched stays empty.

    # 1. Syntax.
    run_check syntax 0 "ls scripts/*.sh | xargs -n1 bash -n && jq -e . hooks/hooks.json >/dev/null"

    # 2. Manifest.
    run_check validate 0 "claude plugin validate ."

    # 3. Guard.
    run_check guard 0 "tests/guard-test.sh"

    # 4. Loop.
    run_check loop 0 "node tests/loop-test.mjs"

    # 5. Prefs.
    run_check prefs 0 "tests/prefs-test.sh"

    # 6. Gate stamp.
    run_check gate 0 "tests/gate-test.sh"

    # 7. Setup.
    run_check setup 0 "tests/setup-test.sh"

    # 8. GitHub wrapper.
    run_check gh 0 "tests/gh-test.sh"

    # 9. Background.
    run_check background 0 "tests/background-test.sh"
fi

echo null > "$work/git.full.json"
echo null > "$work/git.print.json"
if [[ "$mode" != "baseline" ]]; then
    start_sha="$(jq -r '.start_sha' "$snapshot")"
    if ! git cat-file -e "$start_sha^{commit}" 2>/dev/null; then
        log "start_sha $start_sha is not a commit in this repository"
        exit 2
    fi
    # The commit the round started from: the newest one an earlier round of the run already
    # listed. A snapshot without it (the run's first, or an older plugin's) lists from the start.
    round_sha="$(jq -r '.round_sha // empty' "$snapshot")"
    if [[ -z "$round_sha" ]]; then
        round_sha="$start_sha"
    fi
    if ! git cat-file -e "$round_sha^{commit}" 2>/dev/null; then
        log "round_sha $round_sha is not a commit in this repository"
        exit 2
    fi
    log "git block against $start_sha"

    # Everything that differs between the start SHA and the working tree,
    # committed or not, plus untracked files.
    {
        git diff --name-only "$start_sha"
        git ls-files --others --exclude-standard
    } | sort -u > "$work/changed"

    # Allowed = the PR's files + every path the approved plan names (plan_paths, a
    # trailing slash means a prefix) + what every round may touch. "Unexpected" means
    # outside the approved plan.
    {
        jq -r '.files[]' "$snapshot"
        jq -r '.plan_paths // [] | .[]' "$snapshot"
        printf '%s\n' 'agent-os/specs/' 'agent-os/standards/' ${ALWAYS_ALLOWED[@]+"${ALWAYS_ALLOWED[@]}"}
    } | sed 's#^\./##' | grep -v '^$' | sort -u > "$work/allowed"

    is_allowed() {
        local path="$1" entry
        while IFS= read -r entry; do
            if [[ "$entry" == */ ]]; then
                [[ "$path" == "$entry"* ]] && return 0
            elif [[ "$path" == "$entry" ]]; then
                return 0
            fi
        done < "$work/allowed"
        return 1
    }

    outside_allowed() {
        local path
        while IFS= read -r path; do
            is_allowed "$path" || printf '%s\n' "$path"
        done
    }

    outside_allowed < "$work/changed" > "$work/unexpected"

    # Work left uncommitted outside agent-os/specs/ (the round's reply files and snapshot live
    # there by design): the checks above ran against it, and the push would leave it behind.
    tree_state | cut -d' ' -f2- | grep -v '^agent-os/specs/' | sort -u > "$work/uncommitted" || true

    # Every commit since the start for the kept result and the count; the round's own for stdout.
    git log --format='%H%x1f%s' "$start_sha..HEAD" > "$work/commits_all" || true
    git log --format='%H%x1f%s' "$round_sha..HEAD" | cut_subjects > "$work/commits" || true

    diff_lines="$(git diff --numstat "$start_sha" | awk '{ a += ($1 == "-" ? 0 : $1) + ($2 == "-" ? 0 : $2) } END { print a + 0 }')"
    # || true: an untracked file cat cannot read (a symlink to a directory) exits xargs 123, and under
    # pipefail that ended the script before its JSON; the readable files are still counted (#50).
    untracked_lines="$(git ls-files --others --exclude-standard -z | xargs -0 cat 2>/dev/null | wc -l | tr -d ' ')" || true
    diff_lines=$((diff_lines + untracked_lines))

    if [[ "$mode" == "git-only" ]]; then
        echo null > "$work/formatter.json"
    else
        outside_allowed < "$formatter_touched" > "$work/formatter_outside"
        lines_json "$work/formatter_outside" > "$work/formatter.json"
    fi
    # The lists go through files: on a pull request of hundreds of files they are past what one
    # command-line argument may carry.
    lines_json "$work/allowed" > "$work/allowed.json"
    lines_json "$work/changed" > "$work/changed.json"
    lines_json "$work/unexpected" > "$work/unexpected.json"
    lines_json "$work/uncommitted" > "$work/uncommitted.json"
    commits_json "$work/commits_all" > "$work/commits_all.json"
    commits_json "$work/commits" > "$work/commits.json"

    jq -n -c \
        --arg start_sha "$start_sha" --arg round_sha "$round_sha" --argjson diff_lines "$diff_lines" \
        --slurpfile allowed "$work/allowed.json" --slurpfile changed "$work/changed.json" \
        --slurpfile unexpected "$work/unexpected.json" --slurpfile uncommitted "$work/uncommitted.json" \
        --slurpfile commits "$work/commits_all.json" --slurpfile formatter "$work/formatter.json" \
        '{start_sha: $start_sha, round_sha: $round_sha, allowed: $allowed[0], changed_files: $changed[0], unexpected_files: $unexpected[0], uncommitted: $uncommitted[0], commits: $commits[0], diff_lines: $diff_lines, formatter_touched_outside_pr: $formatter[0]}' \
        > "$work/git.full.json"
    jq -n -c \
        --arg start_sha "$start_sha" --arg round_sha "$round_sha" --argjson diff_lines "$diff_lines" \
        --slurpfile allowed "$work/allowed.json" --slurpfile changed "$work/changed.json" \
        --slurpfile unexpected "$work/unexpected.json" --slurpfile uncommitted "$work/uncommitted.json" \
        --slurpfile commits "$work/commits.json" --slurpfile all "$work/commits_all.json" --slurpfile formatter "$work/formatter.json" \
        '{start_sha: $start_sha, round_sha: $round_sha, allowed_count: ($allowed[0] | length), changed_count: ($changed[0] | length), unexpected_files: $unexpected[0], uncommitted: $uncommitted[0], commits: $commits[0], commits_count: ($all[0] | length), diff_lines: $diff_lines, formatter_touched_count: ($formatter[0] | if . == null then null else length end)}' \
        > "$work/git.print.json"

    if [[ -s "$work/unexpected" ]]; then
        failed=1
        log "unexpected files changed: $(wc -l < "$work/unexpected" | tr -d ' ') (git.unexpected_files)"
    fi
    if [[ -s "$work/uncommitted" ]]; then
        failed=1
        log "uncommitted changes outside agent-os/specs/: $(wc -l < "$work/uncommitted" | tr -d ' ') (git.uncommitted)"
    fi
fi

emit_checks

ok="$([[ $failed -eq 0 ]] && echo true || echo false)"

# The result is kept only where the temp directory can be written; a run that cannot keep it still
# prints its result, with "kept" empty, and a --verdict after it finds nothing.
if ! mkdir -p "$kept_dir" 2>/dev/null || [[ ! -w "$kept_dir" ]]; then
    log "the result is not kept: $kept_dir cannot be written"
    kept=""
fi

jq -n -c \
    --arg mode "$mode" --argjson ok "$ok" \
    --slurpfile checks "$checks_full" --slurpfile git "$work/git.full.json" \
    '{mode: $mode, ok: $ok, checks: $checks, git: $git[0]}' \
    > "$work/full.json"
jq -n -c \
    --arg mode "$mode" --argjson ok "$ok" --arg kept "$kept" \
    --slurpfile checks "$checks_print" --slurpfile git "$work/git.print.json" \
